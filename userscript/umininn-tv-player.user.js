            if (automatic && !disposed && ticket !== null && ticket === layoutTicket && epoch === layoutUserEpoch)
                await layoutAudioFlow?.restore(ticket);
            if (!disposed && generation === recoveryStartGeneration) automaticRecoveryReason = null;
