#!/usr/bin/env node
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const RELEASE_VERSION = '1.0.12';
const FILENAME = 'umininn-tv-player.user.js';
const META_FILENAME = 'umininn-tv-player.meta.js';
const DISTRIBUTION_URL = 'https://umininn-gh.github.io/tv/userscript/';
const UPDATE_URL = DISTRIBUTION_URL + META_FILENAME;
const DOWNLOAD_URL = DISTRIBUTION_URL + FILENAME;
const SITE_MATCHES = Object.freeze([
    'https://umininn-gh.github.io/tv/', 'https://umininn-gh.github.io/tv/?*',
    'https://umininn-gh.github.io/tv/index.html*', 'https://umininn-gh.github.io/tv/admin.html*'
]);
const MODULES = Object.freeze([
    ['browser-extension/shared/config.js', 'UmininnConfig'],
    ['browser-extension/shared/media-controller.js', 'UmininnMedia'],
    ['browser-extension/shared/player-recovery.js', 'UmininnRecovery'],
    ['browser-extension/shared/twitch-controller.js', 'UmininnTwitch'],
    ['userscript/angelthump-logo.js', 'UmininnAngelThump'],
    ['browser-extension/site-ui.js', 'UmininnSite'],
    ['userscript/transport.js', 'UmininnUserscript']
].map(entry => Object.freeze(entry)));
const SOURCE_FILES = Object.freeze([...MODULES.map(([file]) => file), 'userscript/bootstrap.js']);

function lstatIfPresent(filename) {
    try { return fs.lstatSync(filename); }
    catch (error) { if (error.code === 'ENOENT') return null; throw error; }
}

function assertNoSymlinkAncestors(filename) {
    let current = path.resolve(filename);
    while (true) {
        if (lstatIfPresent(current)?.isSymbolicLink()) throw new Error('Unsafe symbolic-link path: ' + current);
        const parent = path.dirname(current);
        if (parent === current) return;
        current = parent;
    }
}

function regularFile(filename) {
    assertNoSymlinkAncestors(filename);
    const stat = fs.lstatSync(filename);
    if (!stat.isFile() || stat.isSymbolicLink()) throw new Error('Expected a regular source file: ' + filename);
    return fs.readFileSync(filename, 'utf8').replace(/\r\n?/g, '\n');
}

function sameValues(actual, expected) {
    return Array.isArray(actual) && actual.length === expected.length &&
        [...actual].sort().every((value, index) => value === [...expected].sort()[index]);
}

function productionMatches(configSource) {
    const context = { module: { exports: {} }, URL };
    vm.runInNewContext(configSource, context, { timeout: 1000, filename: SOURCE_FILES[0] });
    const config = context.module.exports;
    const siteMatches = Array.from(config.SITE_MATCHES || []).filter(match => typeof match === 'string' && match.startsWith('https://'));
    const playerHosts = Array.from(config.PLAYER_HOSTS || []);
    if (!sameValues(siteMatches, SITE_MATCHES) || !playerHosts.length || new Set(playerHosts).size !== playerHosts.length ||
        playerHosts.some(host => typeof host !== 'string' || !/^(?:[a-z0-9-]+\.)+[a-z]{2,}$/.test(host) || host.endsWith('.localhost'))) {
        throw new Error('Unexpected production site/player scope in shared config');
    }
    const playerMatches = playerHosts.map(host => 'https://' + host + '/*');
    const configuredPlayerMatches = Array.from(config.PLAYER_MATCHES || []).filter(match => typeof match === 'string' && match.startsWith('https://'));
    if (!sameValues(configuredPlayerMatches, playerMatches)) throw new Error('Unexpected production player match in shared config');
    return [...SITE_MATCHES, ...playerMatches];
}

function metadata(matches) {
    return [
        '// ==UserScript==',
        '// @name         Umininn TV 播放器控制（Userscript）',
        '// @namespace    https://umininn-gh.github.io/tv/',
        '// @version      ' + RELEASE_VERSION,
        '// @description  在 Umininn TV 控制播放器音量、靜音及恢復播放，隱藏 AngelThump 橫幅並自動收起初載控制列。',
        '// @homepageURL  https://umininn-gh.github.io/tv/',
        '// @updateURL    ' + UPDATE_URL,
        '// @downloadURL  ' + DOWNLOAD_URL,
        ...matches.map(match => '// @match        ' + match),
        '// @run-at       document-idle',
        '// @sandbox      DOM',
        '// @inject-into  content',
        '// ==/UserScript==', ''
    ].join('\n');
}

function renderUserscript(options = {}) {
    const projectRoot = path.resolve(options.projectRoot || path.join(__dirname, '..'));
    // Read and validate the complete allowlist before preparing any output.
    const sources = new Map(SOURCE_FILES.map(file => [file, regularFile(path.join(projectRoot, ...file.split('/')))]));
    for (const [file, source] of sources) new vm.Script(source, { filename: file });
    const header = metadata(productionMatches(sources.get(SOURCE_FILES[0])));
    const parts = [header, '/* Generated by tools/build-player-userscript.cjs; edit the source files instead. */',
        '(function () {', "    'use strict';",
        '    const scope = {',
        '        userscriptVersion: ' + JSON.stringify(RELEASE_VERSION) + ',',
        '        window, document, location, AbortController: window.AbortController,',
        '        setTimeout: window.setTimeout.bind(window), clearTimeout: window.clearTimeout.bind(window),',
        '        setInterval: window.setInterval.bind(window), clearInterval: window.clearInterval.bind(window),',
        '        MutationObserver: window.MutationObserver, ResizeObserver: window.ResizeObserver',
        '    };'];
    for (const [file, property] of MODULES) {
        parts.push('', '    // Source: ' + file, '    scope.' + property + ' = (function (globalThis) {',
            '        const module = { exports: {} };', sources.get(file).trimEnd(),
            '        return module.exports;', '    })(scope);');
    }
    parts.push('', '    // Source: userscript/bootstrap.js', sources.get('userscript/bootstrap.js').trimEnd(), '})();', '');
    const script = parts.join('\n');
    new vm.Script(script, { filename: FILENAME });
    return script;
}

function assertRegularDestination(filename) {
    assertNoSymlinkAncestors(filename);
    const stat = lstatIfPresent(filename);
    if (stat && (!stat.isFile() || stat.isSymbolicLink())) {
        throw new Error('Unsafe file destination: ' + filename);
    }
}

function assertOutputDirectory(directory) {
    assertNoSymlinkAncestors(directory);
    const stat = lstatIfPresent(directory);
    if (!stat) return;
    if (!stat.isDirectory()) throw new Error('Unsafe output directory: ' + directory);
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
        if (entry.isSymbolicLink()) throw new Error('Output contains a symbolic link: ' + entry.name);
        if (!entry.isFile() || ![FILENAME, META_FILENAME].includes(entry.name)) {
            throw new Error('Unexpected output file; choose an empty output folder: ' + entry.name);
        }
    }
}

function buildUserscript(options = {}) {
    const projectRoot = path.resolve(options.projectRoot || path.join(__dirname, '..'));
    const outputRoot = path.resolve(options.outputRoot || path.join(projectRoot, 'outputs', 'player-userscript'));
    const relativeOutput = path.relative(projectRoot, outputRoot);
    if (!relativeOutput || relativeOutput === '..' || relativeOutput.startsWith('..' + path.sep) || path.isAbsolute(relativeOutput) ||
        ['userscript', 'browser-extension'].some(directory => relativeOutput === directory || relativeOutput.startsWith(directory + path.sep))) {
        throw new Error('Output directory must be inside the project and separate from source folders');
    }
    const script = renderUserscript({ projectRoot });
    const scriptPath = path.join(outputRoot, FILENAME);
    const metaPath = path.join(outputRoot, META_FILENAME);
    const distributionPath = path.join(projectRoot, 'userscript', FILENAME);
    const distributionMetaPath = path.join(projectRoot, 'userscript', META_FILENAME);
    assertOutputDirectory(outputRoot);
    for (const filename of [scriptPath, metaPath, distributionPath, distributionMetaPath]) assertRegularDestination(filename);
    const header = script.slice(0, script.indexOf('// ==/UserScript==') + '// ==/UserScript=='.length) + '\n';
    fs.mkdirSync(outputRoot, { recursive: true });
    fs.writeFileSync(scriptPath, script, 'utf8');
    fs.writeFileSync(metaPath, header, 'utf8');
    fs.writeFileSync(distributionPath, script, 'utf8');
    fs.writeFileSync(distributionMetaPath, header, 'utf8');
    return { version: RELEASE_VERSION, scriptPath, metaPath, distributionPath, distributionMetaPath, files: SOURCE_FILES.length, bytes: Buffer.byteLength(script) };
}

if (require.main === module) {
    try {
        if (process.argv.length !== 2) throw new Error('Usage: node tools/build-player-userscript.cjs');
        console.log(JSON.stringify(buildUserscript(), null, 2));
    }
    catch (error) { console.error(error.message); process.exitCode = 1; }
}

module.exports = { RELEASE_VERSION, FILENAME, META_FILENAME, UPDATE_URL, DOWNLOAD_URL, SITE_MATCHES, SOURCE_FILES, renderUserscript, buildUserscript };
